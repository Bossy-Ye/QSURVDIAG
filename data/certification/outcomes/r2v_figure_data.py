"""Figure inputs generated from the v2 records (V2_SPECIFICATION.md section 11).

Writes manuscript/data/tse_visual_data_v2.json. Report counts, width outcomes, suite kills
and the interface transition matrix come from R2V_FINAL_*.csv and R2V_ANALYSES.json. The
runtime series of Fig. 6(b) is the v1 recorded run's measurement, copied from the v1 snapshot
with its provenance stated (spec 10); v2 does not re-measure it.
"""
import csv, json, os, sys, collections
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import r2v_lib as V

H = V.HERE; M = V.PA + "manuscript/"
KEYS = ["CL1", "CL2", "CL3", "CL4", "CL5", "Unresolved"]
SUBJECTS = {"construction": ['bv_4', 'bv_5', 'bv_7', 'dj_3', 'dj_4', 'ghz_4', 'ghz_5', 'ghz_7',
                             'grover_3', 'grover_5', 'qft_4', 'qft_5', 'qft_6', 'qpe_5', 'qpe_6'],
            "prospective": ['simon_4', 'wstate_4', 'cuccaro_adder_5', 'swaptest_5', 'toffoli_barenco_5']}

def main():
    v1 = json.load(open(M + "data/tse_visual_data.json"))
    A = json.load(open(os.path.join(H, "R2V_ANALYSES.json")))
    P = list(csv.DictReader(open(os.path.join(H, "R2V_FINAL_PRIMARY.csv"))))
    out = {"provenance": {
        "note": "Generated by revision2/r2v_figure_data.py from the v2 records (V2_SPECIFICATION.md, sha256 "
                + V.SPEC_SHA[:12] + "). Report counts are v2 reports.",
        "scale_costs": "v1 recorded run (B2_SCALE_CELLS_FRESH.jsonl: total_seconds; B_universe + C_relations), "
                       "copied from data/tse_visual_data.json; v2 does not re-measure runtime"}}
    for pop, subs in SUBJECTS.items():
        labels = {r["label"].split(" (")[0]: r["label"] for r in v1[pop]}
        rows = []
        for sub, disp in zip(subs, v1[pop]):
            c = collections.Counter(r["v2_report"] for r in P if r["subject"] == sub and r["v2_report"] != "NA_KILLED")
            rows.append({"subject": sub, "label": disp["label"], "counts": [c[k] for k in KEYS]})
        out[pop] = rows
    W = list(csv.DictReader(open(os.path.join(H, "R2V_FINAL_WIDTH.csv"))))
    so = []
    for n in sorted({int(r["n"]) for r in W}):
        g = [r for r in W if int(r["n"]) == n]; c = collections.Counter(r["v2_report"] for r in g)
        so.append([n, len(g), c["NA_KILLED"], c["CL1"], c["CL3"], c["CL4"], c["CL5"], c["Unresolved"]])
    out["scale_outcomes"] = so
    out["scale_costs"] = v1["scale_costs"]
    out["suite_arm"] = A["suite_arm"]; out["sspec_arm"] = A["sspec_arm"]
    out["interface_matrix"] = A["interface_matrix"]
    out["lattice"] = json.load(open(V.PA + "github/results/recovered/T1_4_LATTICE.json"))["cells"]
    json.dump(out, open(M + "data/tse_visual_data_v2.json", "w"), indent=1)
    supplement_inputs(P)
    print(json.dumps({k: out[k] for k in ("scale_outcomes", "suite_arm", "interface_matrix", "lattice")}, indent=0))

def supplement_inputs(P):
    """Figs. S1 and S2 inputs from the v2 construction records: reports by program, and effect
    compression (unique endpoint states and observations rounded to 9 decimals, keyed by subject;
    the definition of T_DISTINCT_EFFECTS.json)."""
    import numpy as np
    from e1_lib import MUT, orig, nq
    import e1_relations as REL
    fam = {"bv": "bernstein_vazirani", "dj": "deutsch_jozsa", "ghz": "ghz", "grover": "grover", "qft": "qft", "qpe": "qpe"}
    cons = [r for r in P if r["population"] == "construction" and r["v2_report"] != "NA_KILLED"]
    keys6 = ["CL1", "CL2", "CL3", "CL4", "CL5", "Unresolved"]
    rows = []
    for sub in SUBJECTS["construction"]:
        c = collections.Counter(r["v2_report"] for r in cons if r["subject"] == sub)
        rows.append({"family": fam[sub.split("_")[0]], "program": sub,
                     **{("CL6" if k == "Unresolved" else k): c[k] for k in keys6}, "total": sum(c.values())})
    tot = {k: sum(r[k] for r in rows) for k in ("CL1", "CL2", "CL3", "CL4", "CL5", "CL6", "total")}
    rows.append({"family": "", "program": "TOTAL", **tot})
    with open(M + "data/R_fig2a_program_claim_v2.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)
    groups = {}
    for r in cons:
        m = MUT[r["mutant_id"]]; sub = m["subject"]; n = nq[sub]
        sv = np.asarray(REL._sv(m["gates"], n))
        sk = (sub, tuple(np.round(sv.real, 9)), tuple(np.round(sv.imag, 9)))
        ok = (sub, tuple(np.round(np.abs(sv) ** 2, 9)))
        groups.setdefault(r["v2_report"], []).append((sk, ok))
    comp = []
    for k in keys6 + ["ALL"]:
        g = [x for kk, v in groups.items() for x in v] if k == "ALL" else groups.get(k, [])
        st = collections.Counter(x[0] for x in g); ob = collections.Counter(x[1] for x in g)
        raw = len(g)
        comp.append({"claim": "CL6" if k == "Unresolved" else k, "raw": raw, "state": len(st), "obs": len(ob),
                     "r2s": round(raw / len(st), 2) if st else "", "r2o": round(raw / len(ob), 2) if ob else "",
                     "singleton_state": sum(1 for v in st.values() if v == 1),
                     "largest_state": max(st.values()) if st else 0})
    with open(M + "data/R_fig2b_compression_v2.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(comp[0])); w.writeheader(); w.writerows(comp)
    print("program matrix total", tot, "\ncompression", comp)

if __name__ == "__main__":
    main()
